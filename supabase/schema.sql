-- ---------- Tabelas ----------------------------------------------------

create table if not exists public.assets (
  id          bigint generated by default as identity primary key,
  symbol      text not null,
  name        text not null,
  asset_type  text,
  description text,
  constraint assets_symbol_key unique (symbol),
  constraint assets_asset_type_check
    check (asset_type = any (array['index', 'stock', 'crypto']))
);

create table if not exists public.price_history (
  id         bigint generated by default as identity primary key,
  asset_id   bigint references public.assets(id) on delete cascade,
  price      numeric not null,
  "timestamp" timestamptz not null default now(),
  constraint price_history_asset_ts_unique unique (asset_id, "timestamp")
);

create table if not exists public.economic_events (
  id          bigint generated by default as identity primary key,
  event_time  timestamptz not null,
  event_name  text not null,
  country     text not null,
  impact      text,
  note        text,
  created_at  timestamptz not null default now(),
  constraint economic_events_unique unique (country, event_time, event_name),
  constraint economic_events_impact_check
    check (impact = any (array['high', 'medium', 'low']))
);

create index if not exists idx_economic_events_country on public.economic_events (country);
create index if not exists idx_economic_events_time    on public.economic_events (event_time);

-- ---------- RLS: leitura pública, escrita só via service_role -----------

alter table public.assets          enable row level security;
alter table public.price_history   enable row level security;
alter table public.economic_events enable row level security;

drop policy if exists "Leitura pública assets" on public.assets;
create policy "Leitura pública assets"
  on public.assets for select to anon using (true);

drop policy if exists "Leitura pública price_history" on public.price_history;
create policy "Leitura pública price_history"
  on public.price_history for select to anon using (true);

drop policy if exists "Leitura pública economic_events" on public.economic_events;
create policy "Leitura pública economic_events"
  on public.economic_events for select to anon using (true);

-- Reforço (defesa em profundidade): o RLS já bloqueia escrita do anon, mas
-- por padrão o Supabase concede todos os privilégios. Removemos os de escrita.
revoke insert, update, delete, truncate, references, trigger
  on public.assets, public.price_history, public.economic_events
  from anon, authenticated;

